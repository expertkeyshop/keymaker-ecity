const assert = require('node:assert/strict');
const path = require('node:path');
const fs = require('node:fs');
const {pathToFileURL} = require('node:url');
const runtime = process.env.KEYMAKER_NODE_MODULES;
const {chromium} = require(runtime ? path.join(runtime, 'playwright') : 'playwright');
(async () => {
  const browser = await chromium.launch({headless:true, ...(process.env.KEYMAKER_BROWSER ? {executablePath:process.env.KEYMAKER_BROWSER} : {})});
  const page = await browser.newPage({viewport:{width:1440,height:1100}});
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.route('https://fonts.googleapis.com/**', route => route.abort());
  await page.goto(pathToFileURL(path.join(__dirname, 'index.html')).href);
  await page.evaluate(() => localStorage.removeItem('keymaker-gbp-v1'));
  await page.reload();
  await page.waitForSelector('.task-checkbox');
  assert.equal(await page.locator('.task-checkbox').count(), 16);
  assert.equal(await page.locator('#doneCount').textContent(), '0');
  await page.locator('#task-name .task-checkbox').check();
  assert.equal(await page.locator('#doneCount').textContent(), '1');
  assert.equal(await page.locator('[role="progressbar"]').getAttribute('aria-valuenow'), '1');
  await page.reload();
  assert.equal(await page.locator('#doneCount').textContent(), '1');
  assert.equal(await page.locator('#task-name .task-checkbox').isChecked(), true);
  await page.locator('[data-filter="done"]').click();
  assert.equal(await page.locator('.task-row').count(), 1);
  await page.locator('#task-name .task-checkbox').uncheck();
  assert.match(await page.locator('.empty-state').textContent(), /completed tasks/);
  await page.locator('#nextTask').click();
  assert.equal(await page.locator('#task-name .task-expand').getAttribute('aria-expanded'), 'true');
  await page.locator('#task-description .task-expand').click();
  await page.locator('#detail-description a[href="#drafts"]').click();
  assert.equal(await page.locator('#view-drafts').isVisible(), true);
  const originalDraft = await page.locator('#description').inputValue();
  assert(originalDraft.length < 750);
  await page.locator('#description').fill(originalDraft + ' ');
  await page.reload();
  assert.equal(await page.locator('#description').inputValue(), originalDraft + ' ');
  assert.equal(await page.locator('#charCount').textContent(), `${originalDraft.length + 1} / 750 characters`);
  let copied = '';
  await page.exposeFunction('captureClipboard', text => { copied = text; });
  await page.evaluate(() => Object.defineProperty(navigator, 'clipboard', {configurable:true, value:{writeText:text => window.captureClipboard(text)}}));
  await page.locator('#copyDescription').click();
  await page.waitForFunction(() => document.querySelector('#toast').textContent.includes('Copied'));
  assert.equal(copied, originalDraft + ' ');
  await page.locator('[data-view="profile"]').click();
  assert.equal(await page.locator('#serviceAreas span').count(), 20);
  await page.locator('[data-view="resources"]').click();
  assert.equal(await page.locator('#sourceLinks a').count(), 6);
  await page.locator('[data-view="checklist"]').click();
  await page.locator('#task-name .task-checkbox').check();
  await page.locator('#reset').click();
  await page.getByRole('button', {name:'Keep my progress'}).click();
  assert.equal(await page.locator('#doneCount').textContent(), '1');
  await page.locator('#reset').click();
  await page.locator('#confirmReset').click();
  await page.waitForFunction(() => document.querySelector('#doneCount').textContent === '0');
  const downloadEvent = page.waitForEvent('download');
  await page.locator('#export').click();
  const download = await downloadEvent;
  assert.equal(download.suggestedFilename(), 'keymaker-google-profile-checklist.txt');
  const exportText = fs.readFileSync(await download.path(), 'utf8');
  assert(exportText.includes('SERVICE DRAFTS') && exportText.includes('DESCRIPTION DRAFT'));
  assert.equal((exportText.match(/\[ \]/g) || []).length, 16);
  await page.evaluate(() => localStorage.removeItem('keymaker-gbp-v1'));
  await page.reload();
  await page.screenshot({path:path.join(__dirname,'preview-desktop.png'), fullPage:true});
  for (const width of [1440,1024,768,390,360]) {
    await page.setViewportSize({width,height:1000});
    for (const view of ['checklist','profile','drafts','resources']) {
      await page.locator(`[data-view="${view}"]`).click();
      assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), `Overflow on ${view} at ${width}px`);
    }
  }
  await page.locator('[data-view="checklist"]').click();
  await page.screenshot({path:path.join(__dirname,'preview-mobile.png'),fullPage:true});
  await page.setViewportSize({width:1440,height:1100});
  for (const checkbox of await page.locator('.task-checkbox').all()) await checkbox.check();
  assert.equal(await page.locator('#doneCount').textContent(), '16');
  assert.equal(await page.locator('#percent').textContent(), '100%');
  assert.equal(await page.locator('#nextTask').isVisible(), false);
  assert.equal(errors.length, 0, errors.join('\n'));
  await page.evaluate(() => localStorage.removeItem('keymaker-gbp-v1'));
  await browser.close();
  console.log('PASS: 16 tasks; progress persistence; filters; task expansion; navigation; editable drafts; copy; reset cancel/confirm; export contents; 20 service areas; desktop and mobile layout across four views; all-complete state; no browser errors.');
})().catch(error => { console.error(error); process.exit(1); });
